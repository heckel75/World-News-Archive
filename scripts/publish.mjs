import fs from 'node:fs/promises';
import path from 'node:path';
import {root,writeExclusive,readEditions} from '../lib/store.mjs';
import {assert} from '../lib/validate.mjs';
import {checkPublication} from '../lib/publish.mjs';
const args=process.argv.slice(2),file=args.find(a=>!a.startsWith('--'));
assert(file,'Usage: node scripts/publish.mjs draft.json --agent-reviewed|--human-reviewed --reviewer=NAME');
const modes=args.filter(a=>['--agent-reviewed','--human-reviewed'].includes(a));
assert(modes.length===1,'Select exactly one explicit review mode');
const reviewer=args.find(a=>a.startsWith('--reviewer='))?.slice(11);
const ed=JSON.parse(await fs.readFile(path.resolve(root,file),'utf8'));
const editions=await readEditions();
checkPublication(ed,{reviewMode:modes[0].slice(2),reviewer,existing:editions.find(d=>d.date===ed.date)});
await writeExclusive(path.join(root,'content','editions',ed.date,`v${ed.revision.number}.json`),ed);
console.log(`Published immutable edition ${ed.date} v${ed.revision.number}. Commit and deploy to make it visible.`);
